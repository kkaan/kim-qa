def test_summary_baseline_session_uses_hex_t_and_labels(tmp_path):
    """A baseline-GT session's summary shows the baseline label, the no-centroid
    note, and metrics computed against the baseline's irregular timebase (the
    fixture pair coincides at offset 0.5 -> near-zero residuals)."""
    make_baseline_pair(tmp_path)
    cfg = ServerConfig(root=tmp_path)
    overrides = {"2026-08-07-Pat03": "baseline:2026_06_17-pat03"}
    sessions = discover_sessions(cfg, overrides)
    update_entry(tmp_path, "2026-08-07-Pat03",
                 {"offset": 0.5, "ranges": [],
                  "hex_override": "baseline:2026_06_17-pat03",
                  "gantry_remap": True})
    text = regenerate_summary(tmp_path, sessions, "Elekta").read_text(
        encoding="utf-8")
    assert "baseline 2026_06_17-pat03 (gantry-remapped)" in text
    assert "Centroid: none (offset 0)" in text or \
        "**Centroid:** none (offset 0)" in text
    lr_line = next(ln for ln in text.splitlines() if ln.startswith("| LR |"))
    # residuals near zero -> no red span on the LR row
    assert RED not in lr_line
    assert "| LR | +0.0" in lr_line or "| LR | -0.0" in lr_line


def test_summary_red_spans_on_failing_axes(tmp_path):
    """A large constant AP bias (flat-zero session -> residuals == KIM values)
    must wrap the failing AP mean in the red span, while a passing LR value and
    the whole 3D row stay unwrapped. Numbers themselves are unchanged."""
    name = "Static,BigBias_1600"
    sess = tmp_path / name
    sess.mkdir(parents=True, exist_ok=True)
    t = np.arange(0.0, 20.0, 1.0)
    z = np.zeros(20)
    # write_kim_file(path, t, ap, lr, si): AP=+5 fails |mean|>1, LR=+0.1 passes.
    write_kim_file(sess / "MarkerLocations_CouchShift_0.txt",
                   t, z + 5.0, z + 0.1, z)
    write_centroid_file(sess / "Phantom_Centroid.txt")
    cfg = ServerConfig(root=tmp_path)
    sessions = discover_sessions(cfg)
    update_entry(tmp_path, name, {"offset": 0.0, "ranges": []})
    text = regenerate_summary(tmp_path, sessions, "Elekta").read_text(
        encoding="utf-8")

    # Detail table: failing AP mean wrapped; passing LR mean plain.
    assert f'| AP | {RED}+5.000</span> |' in text
    assert '| LR | +0.100 |' in text
    # 3D row is never colored, even though its magnitude (~5 mm) "fails".
    line_3d = next(ln for ln in text.splitlines() if ln.startswith('| 3D |'))
    assert RED not in line_3d
    # Overview table: failing AP mean wrapped, kept next to its ± std.
    assert f'{RED}+5.00</span>±0.00' in text
