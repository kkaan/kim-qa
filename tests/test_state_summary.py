def test_summary_includes_offline_overlays(tmp_path):
    """A nested kim-log* folder gets its own overview row and detail metrics
    table, computed with its saved per-offline offset (not the primary's)."""
    traces = tmp_path / "Motion traces"
    sess = make_motion_session(tmp_path, traces)
    # Offline replay on its own timebase: sampled from the hex at +5 s, with a
    # constant +0.3 mm LR bias so its metrics differ visibly from the primary.
    off_dir = sess / "kim-log-pdf480"
    off_dir.mkdir()
    t = np.arange(100) * 0.25
    u = t + 5.0
    si = 2.0 * np.sin(2 * np.pi * 0.2 * u) + 0.1 * u
    lr = 0.2 * np.sin(2 * np.pi * 0.1 * u) + 0.3
    ap = 0.5 * np.sin(2 * np.pi * 0.15 * u)
    write_ga_file(off_dir / "MarkerLocationsGA_CouchShift_0.txt", t, ap, lr, si,
                  np.linspace(180.0, 100.0, len(t)))
    cfg = ServerConfig(root=tmp_path)
    sessions = discover_sessions(cfg)
    update_entry(tmp_path, "lung-typical,Test_1518",
                 {"offset": 3.0, "ranges": [],
                  "offline_offsets": {"kim-log-pdf480": 5.0}})
    text = regenerate_summary(tmp_path, sessions, "Elekta").read_text(
        encoding="utf-8")

    # Overview: one extra row for the offline run, at its own offset.
    row = next(ln for ln in text.splitlines()
               if ln.startswith("| lung-typical,Test_1518 / pdf480 |"))
    assert "| offline | +5.00 |" in row
    # Detail: a subsection with its own metrics table showing the LR bias.
    assert "### Offline: pdf480" in text
    idx = text.index("### Offline: pdf480")
    lr_line = next(ln for ln in text[idx:].splitlines()
                   if ln.startswith("| LR |"))
    assert "+0.300" in lr_line


